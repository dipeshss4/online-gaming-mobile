"""
Packs the game tiles from scripts/render-tiles.py for the app and the website, and writes the lists both read.

    python3 scripts/pack-tiles.py <render-dir>

App: assets/tiles/<CODE>.jpg (600x500) and src/tileArt.ts, and the opening screen's assets/intro/INTRO_*.jpg. Website: frontend/public/art/tiles/<CODE>.jpg (720x600)
and frontend/src/tileArt.ts. Both lists are generated here, so they always match the renders.

In-game art, when rendered: each game's scene (BG_<CODE>, a JPEG behind the reels) and 3D logo (LOGO_<CODE>, trimmed to its
letters with a clear background), to assets/scenes/ + assets/logos/ and public/art/scenes/ + public/art/logos/, listed in
src/sceneArt.ts and frontend/src/sceneArt.ts.
"""
import os, sys
from PIL import Image

RENDERS = sys.argv[1] if len(sys.argv) > 1 else 'renders'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
codes = sorted(f[5:-4] for f in os.listdir(RENDERS) if f.startswith('TILE_') and f.endswith('.png'))

# Each kind is packed (and its list rewritten) only when the folder has renders of it.
if codes:
    for folder, size in (('assets/tiles', (600, 500)), ('../frontend/public/art/tiles', (720, 600))):
        out = os.path.join(ROOT, folder); os.makedirs(out, exist_ok=True)
        for code in codes:
            art = Image.open(os.path.join(RENDERS, f'TILE_{code}.png')).convert('RGB').resize(size, Image.LANCZOS)
            art.save(os.path.join(out, f'{code}.jpg'), quality=84, optimize=True, progressive=True)
        print('wrote', folder, len(codes), 'tiles,', sum(os.path.getsize(os.path.join(out, f'{c}.jpg')) for c in codes) // 1024, 'KB')

for name, size in (('INTRO_WIDE', (1600, 900)), ('INTRO_TALL', (900, 1600))):
    source = os.path.join(RENDERS, f'{name}.png')
    if not os.path.exists(source): continue
    out = os.path.join(ROOT, 'assets/intro'); os.makedirs(out, exist_ok=True)
    Image.open(source).convert('RGB').resize(size, Image.LANCZOS).save(os.path.join(out, f'{name}.jpg'), quality=80, optimize=True, progressive=True)
    print('wrote assets/intro', name)

HEADER = '// Generated by mobile/scripts/pack-tiles.py from the renders of scripts/render-tiles.py. Do not edit.\n'
if codes:
    with open(os.path.join(ROOT, 'src/tileArt.ts'), 'w') as f:
        f.write(HEADER + '/** Each game\'s rendered lobby tile (6:5, its name drawn in), by game code. */\n')
        f.write('export const TILE_ART: Record<string, number> = {\n')
        for code in codes: f.write(f"  {code}: require('../assets/tiles/{code}.jpg'),\n")
        f.write('};\n')
    with open(os.path.join(ROOT, '../frontend/src/tileArt.ts'), 'w') as f:
        f.write(HEADER + '/** The games with a rendered lobby tile in public/art/tiles (6:5, its name drawn in). */\n')
        f.write('export const TILE_ART = new Set([\n' + ''.join(f"  '{code}',\n" for code in codes) + '])\n')
        f.write("export const tileArtUrl = (code: string) => TILE_ART.has(code) ? `/art/tiles/${code}.jpg` : null\n")
    print('wrote src/tileArt.ts and frontend/src/tileArt.ts')

scenes = sorted(f[3:-4] for f in os.listdir(RENDERS) if f.startswith('BG_') and f.endswith('.png'))
logos = {}
for folder, size in (('assets/scenes', (1280, 720)), ('../frontend/public/art/scenes', (1600, 900))):
    out = os.path.join(ROOT, folder); os.makedirs(out, exist_ok=True)
    for code in scenes:
        Image.open(os.path.join(RENDERS, f'BG_{code}.png')).convert('RGB').resize(size, Image.LANCZOS).save(os.path.join(out, f'{code}.jpg'), quality=80, optimize=True, progressive=True)
    if scenes: print('wrote', folder, len(scenes), 'scenes,', sum(os.path.getsize(os.path.join(out, f'{c}.jpg')) for c in scenes) // 1024, 'KB')
for folder, longest in (('assets/logos', 560), ('../frontend/public/art/logos', 720)):
    out = os.path.join(ROOT, folder); os.makedirs(out, exist_ok=True)
    for f in sorted(os.listdir(RENDERS)):
        if not (f.startswith('LOGO_') and f.endswith('.png')): continue
        code = f[5:-4]
        art = Image.open(os.path.join(RENDERS, f)).convert('RGBA')
        art = art.crop(art.getchannel('A').point(lambda a: 255 if a > 10 else 0).getbbox())
        k = longest / art.width; art = art.resize((longest, round(art.height * k)), Image.LANCZOS)
        art.save(os.path.join(out, f'{code}.png'), optimize=True)
        logos[code] = round(art.width / art.height, 3)
    if logos: print('wrote', folder, len(logos), 'logos,', sum(os.path.getsize(os.path.join(out, f'{c}.png')) for c in logos) // 1024, 'KB')
if not (codes or scenes or logos): sys.exit(f'no renders in {RENDERS}')
if scenes or logos:
    with open(os.path.join(ROOT, 'src/sceneArt.ts'), 'w') as f:
        f.write(HEADER + '/** Each game\'s rendered scene, drawn behind its reels (16:9). */\n')
        f.write('export const SCENE_ART: Record<string, number> = {\n' + ''.join(f"  {c}: require('../assets/scenes/{c}.jpg'),\n" for c in scenes) + '};\n')
        f.write('/** Each game\'s 3D logo (a clear background), with its width over height. */\n')
        f.write('export const LOGO_ART: Record<string, { source: number; ratio: number }> = {\n' + ''.join(f"  {c}: {{ source: require('../assets/logos/{c}.png'), ratio: {r} }},\n" for c, r in sorted(logos.items())) + '};\n')
    with open(os.path.join(ROOT, '../frontend/src/sceneArt.ts'), 'w') as f:
        f.write(HEADER + '/** The games with a rendered scene (public/art/scenes, 16:9) and a 3D logo (public/art/logos). */\n')
        f.write('const SCENES = new Set([' + ', '.join(f"'{c}'" for c in scenes) + '])\n')
        f.write('const LOGOS: Record<string, number> = {' + ', '.join(f'{c}: {r}' for c, r in sorted(logos.items())) + '}\n')
        f.write("export const sceneUrl = (code: string) => SCENES.has(code) ? `/art/scenes/${code}.jpg` : null\n")
        f.write("export const logoArt = (code: string) => LOGOS[code] ? { url: `/art/logos/${code}.png`, ratio: LOGOS[code] } : null\n")
    print('wrote src/sceneArt.ts and frontend/src/sceneArt.ts')
