"""
Packs the fish tables' art from scripts/render-fish.py and scripts/render-seabeds.py for the app and the website.

    python3 scripts/pack-fish.py <render-dir>

Each creature's eight frames become one sheet (4 across, 2 down, WebP with a clear background) at
assets/fish/<TABLE>/<CODE>.webp and frontend/public/art/fish/<TABLE>/<CODE>.webp; each sea floor is graded for the
water (its tint, darker towards the edges) to assets/fish/<TABLE>/SEABED.jpg; the caustics tile goes to
assets/fish/CAUSTICS.png. The lists both games read, src/fish/sprites.ts and frontend/src/fishSprites.ts, are written
here from what was packed, so they always match the art.
"""
import os, sys
from PIL import Image, ImageChops, ImageDraw, ImageFilter

RENDERS = sys.argv[1] if len(sys.argv) > 1 else 'renders'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP, WEB = os.path.join(ROOT, 'assets/fish'), os.path.join(ROOT, '../frontend/public/art/fish')
COLS, ROWS, FRAMES = 4, 2, 8
# Each table's water: the tint laid over its floor and how much, and how dark the edges fall away.
WATER = {'DRAGON_TIDE': ((30, 175, 205), .2, .55), 'KRAKENS_DEEP': ((20, 8, 50), .22, .7), 'SHARK_FRENZY': ((40, 170, 200), .3, .45)}

sheets = {}
for name in sorted(os.listdir(RENDERS)):
    if not (name.startswith('FISH_') and name.endswith('.box')): continue
    key = name[5:-4]; table = next(t for t in WATER if key.startswith(t + '_')); code = key[len(table) + 1:]
    kind, w, h = open(os.path.join(RENDERS, name)).read().split()
    frames = [Image.open(os.path.join(RENDERS, f'FISH_{key}_{i}.png')).convert('RGBA') for i in range(FRAMES)]
    fw, fh = frames[0].size
    sheet = Image.new('RGBA', (fw * COLS, fh * ROWS))
    for i, f in enumerate(frames): sheet.paste(f, ((i % COLS) * fw, (i // COLS) * fh))
    for out in (APP, WEB):
        os.makedirs(os.path.join(out, table), exist_ok=True)
        sheet.save(os.path.join(out, table, f'{code}.webp'), 'WEBP', quality=84, method=4)
    sheets.setdefault(table, {})[code] = dict(kind=kind, w=float(w), h=float(h), fw=fw, fh=fh)

seabeds = []
for table, (tint, amount, edge) in WATER.items():
    source = os.path.join(RENDERS, f'SEABED_{table}.png')
    if not os.path.exists(source): continue
    img = Image.open(source).convert('RGB').resize((1600, 900), Image.LANCZOS)
    # The water's colour over everything, then the edges falling into the deep.
    img = Image.blend(img, ImageChops.multiply(img, Image.new('RGB', img.size, tint)).point(lambda v: min(255, int(v * 2.2))), amount)
    mask = Image.new('L', img.size, 0); ImageDraw.Draw(mask).ellipse((60, 40, 1540, 860), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(200))
    dark = Image.blend(img, Image.new('RGB', img.size, tuple(int(c * .25) for c in tint)), edge)
    img = Image.composite(img, dark, mask)
    for out in (APP, WEB):
        os.makedirs(os.path.join(out, table), exist_ok=True); img.save(os.path.join(out, table, 'SEABED.jpg'), quality=84, optimize=True, progressive=True)
    seabeds.append(table)

# Cannons: three tiers of turret per table, and the seat it turns on (flipped so its dome faces up into the table).
cannons = []
for table in WATER:
    if not all(os.path.exists(os.path.join(RENDERS, f'CANNON_{table}_{i}.png')) for i in range(3)): continue
    for out in (APP, WEB):
        os.makedirs(os.path.join(out, table), exist_ok=True)
        for i in range(3): Image.open(os.path.join(RENDERS, f'CANNON_{table}_{i}.png')).convert('RGBA').save(os.path.join(out, table, f'CANNON_{i}.webp'), 'WEBP', quality=86, method=4)
        Image.open(os.path.join(RENDERS, f'SEAT_{table}.png')).convert('RGBA').transpose(Image.FLIP_TOP_BOTTOM).save(os.path.join(out, table, 'SEAT.webp'), 'WEBP', quality=86, method=4)
    cannons.append(table)

caustics = os.path.exists(os.path.join(RENDERS, 'CAUSTICS.png'))
if caustics:
    tile = Image.open(os.path.join(RENDERS, 'CAUSTICS.png')).convert('RGBA')
    for out in (APP, WEB): os.makedirs(out, exist_ok=True); tile.save(os.path.join(out, 'CAUSTICS.png'), optimize=True)

def ts(source):
    lines = ["/** Generated by scripts/pack-fish.py from the fish renders: do not edit by hand. */",
             "export type FishSheet = { source: " + ("number" if source(None, None) == 'app' else "string") + "; kind: 'side' | 'top'; w: number; h: number; fw: number; fh: number }",
             "/** Each table's creatures: a sheet of 8 frames, 4 across and 2 down; w and h are its size in render units. */",
             "export const FISH_SHEETS: Record<string, Record<string, FishSheet>> = {"]
    for table in sorted(sheets):
        lines.append(f"  {table}: {{")
        for code, m in sorted(sheets[table].items()):
            lines.append(f"    {code}: {{ source: {source(table, code)}, kind: '{m['kind']}', w: {m['w']}, h: {m['h']}, fw: {m['fw']}, fh: {m['fh']} }},")
        lines.append("  },")
    lines.append("}")
    lines.append("export const SEABEDS: Record<string, " + ("number" if source(None, None) == 'app' else "string") + "> = {")
    for table in seabeds: lines.append(f"  {table}: {source(table, 'SEABED')},")
    lines.append("}")
    kind = "number" if source(None, None) == 'app' else "string"
    lines.append(f"/** Each table's cannon: its turret in three tiers (the pivot in the middle, pointing right) and the seat it turns on. */")
    lines.append(f"export const CANNONS: Record<string, {{ tiers: [{kind}, {kind}, {kind}]; seat: {kind} }}> = {{")
    for table in cannons: lines.append(f"  {table}: {{ tiers: [{', '.join(source(table, f'CANNON_{i}') for i in range(3))}], seat: {source(table, 'SEAT')} }},")
    lines.append("}")
    if caustics: lines.append(f"export const CAUSTICS = {source('', 'CAUSTICS')}")
    return '\n'.join(lines) + '\n'

def app(table, code):
    if table is None: return 'app'
    if code == 'CAUSTICS': return "require('../../assets/fish/CAUSTICS.png')"
    return f"require('../../assets/fish/{table}/{code}.{'jpg' if code == 'SEABED' else 'webp'}')"

def web(table, code):
    if table is None: return 'web'
    if code == 'CAUSTICS': return "'/art/fish/CAUSTICS.png'"
    return f"'/art/fish/{table}/{code}.{'jpg' if code == 'SEABED' else 'webp'}'"

if sheets:
    open(os.path.join(ROOT, 'src/fish/sprites.ts'), 'w').write(ts(app))
    open(os.path.join(ROOT, '../frontend/src/fishSprites.ts'), 'w').write(ts(web))
total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(APP) for f in fs)
print('packed', sum(len(v) for v in sheets.values()), 'sheets,', len(seabeds), 'sea floors,', total // 1024, 'KB')
